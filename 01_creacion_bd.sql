-- ---------------------------------------------------------------------
-- Limpieza previa (borra tablas y datos para recrear desde cero)
-- ---------------------------------------------------------------------
DROP TABLE IF EXISTS restauracion, empleado_funcion, funcion_empleado,
                     empleado, copia, obra, sala, autor CASCADE;
DROP DOMAIN IF EXISTS t_id, t_dni, t_tipo_sala, t_sensibilidad CASCADE;

-- ---------------------------------------------------------------------
-- Dominios
-- ---------------------------------------------------------------------

-- Identificador numérico de cada tabla.
-- PostgreSQL no permite IDENTITY sobre un dominio, por eso las PK
-- autoincrementales son INTEGER con un CHECK (> 0) equivalente; t_id se
-- usa en las claves foráneas.
CREATE DOMAIN t_id AS INTEGER
    CONSTRAINT ck_t_id CHECK (VALUE > 0);

-- Número de documento de un empleado
CREATE DOMAIN t_dni AS INTEGER
    CONSTRAINT ck_t_dni CHECK (VALUE BETWEEN 0 AND 99999999);

-- Tipos de sala admitidos en el museo
CREATE DOMAIN t_tipo_sala AS VARCHAR(20)
    CONSTRAINT ck_t_tipo_sala CHECK (VALUE IN ('muestra', 'almacenamiento'));

-- Sensibilidades de obra y especializaciones de sala
CREATE DOMAIN t_sensibilidad AS VARCHAR(20)
    CONSTRAINT ck_t_sensibilidad CHECK (VALUE IN ('humedad', 'fotosensibilidad'));

-- ---------------------------------------------------------------------
-- Tabla: AUTOR
-- ---------------------------------------------------------------------
CREATE TABLE autor (
    id_autor    INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    nombre      VARCHAR(40)  NOT NULL,
    apellido    VARCHAR(40)  NOT NULL,
    CONSTRAINT pk_autor PRIMARY KEY (id_autor),
    CONSTRAINT ck_autor_id CHECK (id_autor > 0)
);

-- ---------------------------------------------------------------------
-- Tabla: SALA
-- ---------------------------------------------------------------------
CREATE TABLE sala (
    id_sala          INTEGER         GENERATED BY DEFAULT AS IDENTITY,
    nombre           VARCHAR(200)    NOT NULL,
    tipo             t_tipo_sala     NOT NULL DEFAULT 'almacenamiento',
    especializacion  t_sensibilidad  NOT NULL,
    CONSTRAINT pk_sala PRIMARY KEY (id_sala),
    CONSTRAINT ck_sala_id CHECK (id_sala > 0)
);

-- ---------------------------------------------------------------------
-- Tabla: OBRA
-- Reglas que dependen de SALA (sala de almacenamiento y especialización
-- igual a la sensibilidad) se controlan con trg_obra_sala_valida.
-- ---------------------------------------------------------------------
CREATE TABLE obra (
    id_obra         INTEGER         GENERATED BY DEFAULT AS IDENTITY,
    nombre          VARCHAR(200)    NOT NULL,
    fecha_creacion  DATE            NOT NULL,
    fecha_rec       DATE            NOT NULL DEFAULT CURRENT_DATE,
    descripcion     TEXT            NULL,
    sensibilidad    t_sensibilidad  NOT NULL,
    id_autor        t_id            NOT NULL,
    id_sala         t_id            NOT NULL,
    CONSTRAINT pk_obra PRIMARY KEY (id_obra),
    CONSTRAINT ck_obra_id CHECK (id_obra > 0),
    CONSTRAINT fk_obra_autor FOREIGN KEY (id_autor) REFERENCES autor (id_autor),
    CONSTRAINT fk_obra_sala  FOREIGN KEY (id_sala)  REFERENCES sala (id_sala),
    CONSTRAINT ck_obra_fecha_creacion CHECK (fecha_creacion <= fecha_rec),
    CONSTRAINT ck_obra_fecha_rec      CHECK (fecha_rec <= CURRENT_DATE)
);

-- ---------------------------------------------------------------------
-- Tabla: COPIA
-- fecha_creacion = OBRA.fecha_rec + 1 mes: la calcula trg_copia_fecha_creacion.
-- Copia almacenada en la misma sala que el original: trg_copia_ubicacion.
-- ---------------------------------------------------------------------
CREATE TABLE copia (
    id_copia        INTEGER  GENERATED BY DEFAULT AS IDENTITY,
    fecha_creacion  DATE     NOT NULL,
    id_obra         t_id     NOT NULL,
    id_sala         t_id     NOT NULL,
    CONSTRAINT pk_copia PRIMARY KEY (id_copia),
    CONSTRAINT ck_copia_id CHECK (id_copia > 0),
    CONSTRAINT fk_copia_obra FOREIGN KEY (id_obra) REFERENCES obra (id_obra),
    CONSTRAINT fk_copia_sala FOREIGN KEY (id_sala) REFERENCES sala (id_sala)
);

-- ---------------------------------------------------------------------
-- Tabla: EMPLEADO
-- ---------------------------------------------------------------------
CREATE TABLE empleado (
    dni            t_dni        NOT NULL,
    nombre         VARCHAR(40)  NOT NULL,
    apellido       VARCHAR(40)  NOT NULL,
    fecha_nac      DATE         NOT NULL,
    telefono       VARCHAR(20)  NULL,
    email          VARCHAR(40)  NULL,
    fecha_ingreso  DATE         NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT pk_empleado PRIMARY KEY (dni),
    CONSTRAINT ck_empleado_fecha_nac     CHECK (fecha_nac < CURRENT_DATE),
    CONSTRAINT ck_empleado_fecha_ingreso CHECK (fecha_ingreso > fecha_nac
                                                AND fecha_ingreso <= CURRENT_DATE)
);

-- ---------------------------------------------------------------------
-- Tabla: FUNCION_EMPLEADO
-- ---------------------------------------------------------------------
CREATE TABLE funcion_empleado (
    id_funcion   INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    descripcion  VARCHAR(40)  NOT NULL,
    CONSTRAINT pk_funcion_empleado PRIMARY KEY (id_funcion),
    CONSTRAINT ck_funcion_empleado_id CHECK (id_funcion > 0)
);

-- ---------------------------------------------------------------------
-- Tabla: EMPLEADO_FUNCION (asociación empleado - función)
-- ---------------------------------------------------------------------
CREATE TABLE empleado_funcion (
    dni_empleado  t_dni  NOT NULL,
    id_funcion    t_id   NOT NULL,
    CONSTRAINT pk_empleado_funcion PRIMARY KEY (dni_empleado, id_funcion),
    CONSTRAINT fk_empleado_funcion_empleado FOREIGN KEY (dni_empleado)
        REFERENCES empleado (dni),
    CONSTRAINT fk_empleado_funcion_funcion  FOREIGN KEY (id_funcion)
        REFERENCES funcion_empleado (id_funcion)
);

-- ---------------------------------------------------------------------
-- Tabla: RESTAURACION
-- fecha_ingreso >= OBRA.fecha_rec, empleado con función 'restauracion' y
-- no superposición de restauraciones se controlan con triggers.
-- ---------------------------------------------------------------------
CREATE TABLE restauracion (
    id_restauracion  INTEGER  GENERATED BY DEFAULT AS IDENTITY,
    fecha_ingreso    DATE     NOT NULL DEFAULT CURRENT_DATE,
    fecha_fin        DATE     NULL,
    id_obra          t_id     NOT NULL,
    dni_empleado     t_dni    NOT NULL,
    CONSTRAINT pk_restauracion PRIMARY KEY (id_restauracion),
    CONSTRAINT ck_restauracion_id CHECK (id_restauracion > 0),
    CONSTRAINT fk_restauracion_obra     FOREIGN KEY (id_obra)
        REFERENCES obra (id_obra),
    CONSTRAINT fk_restauracion_empleado FOREIGN KEY (dni_empleado)
        REFERENCES empleado (dni),
    CONSTRAINT ck_restauracion_fecha_fin CHECK (fecha_fin IS NULL
                                                OR fecha_fin >= fecha_ingreso)
);
